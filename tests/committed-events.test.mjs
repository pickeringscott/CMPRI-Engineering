import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import {changedResources} from '../src/lib/events/resources.ts';
const sql=readFileSync('supabase/migrations/20261027190000_cmpri_committed_resource_events.sql','utf8');
const hotel='00000000-0000-4000-8000-000000000001', user='00000000-0000-4000-8000-000000000002', other='00000000-0000-4000-8000-000000000003';
test('durable revision migration: commit/rollback/coalescing, private signals, queue leases and immutable snapshot guard',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create schema auth; create role anon; create role authenticated; create role service_role bypassrls;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
 create function auth.role() returns text language sql stable as $$ select 'service_role'::text $$;
 create table hotels(id uuid primary key);
 create table profiles(id uuid primary key,active boolean);
 create table hotel_members(hotel_id uuid,user_id uuid,active boolean);
 create table work_orders(id uuid primary key,hotel_id uuid,issue text);
 create table cmpri_work_order_history(id uuid primary key,hotel_id uuid,event_type text);
 create table cmpri_work_order_technician_views(id uuid primary key,hotel_id uuid);
 create table user_feedback(id uuid primary key,hotel_id uuid);
 create table room_operations(id uuid primary key,hotel_id uuid,room_status text);
 create table cmpri_room_operation_imports(id uuid primary key,hotel_id uuid,report_date date,source_type text,uploaded_at timestamptz);
 insert into hotels values ('${hotel}'); insert into auth.users values ('${user}'),('${other}');
 insert into profiles values ('${user}',true),('${other}',true);
 insert into hotel_members values ('${hotel}','${user}',true),('${hotel}','${other}',true);`);
 await db.exec(sql);
 await db.exec(sql); // migration replay retains identities, no historical notification backfill
 assert.equal((await db.query('select count(*)::int as n from cmpri_notification_events')).rows[0].n,0);
 const importId='00000000-0000-4000-8000-000000000004';
 await db.query("insert into cmpri_room_operation_imports(id,hotel_id,report_date,source_type,uploaded_at) values($1,$2,'2026-10-27','file',now())",[importId,hotel]);
 assert.equal((await db.query("select revision from cmpri_resource_revisions where resource='room-operations'")).rows[0].revision,importId);
 await db.query("update cmpri_room_operation_imports set uploaded_at=now() where id=$1",[importId]);
 assert.equal((await db.query("select revision from cmpri_resource_revisions where resource='room-operations'")).rows[0].revision,importId,'no unchanged-snapshot invalidation');
 const revision=async()=> (await db.query("select revision from cmpri_resource_revisions where resource='work-orders'")).rows[0].revision;
 const before=await revision();
 await db.exec("begin; insert into work_orders values(gen_random_uuid(),'"+hotel+"','first'); update work_orders set issue='second';");
 const during=await revision();assert.notEqual(during,before);
 await db.exec("update work_orders set issue='third'");assert.equal(await revision(),during);
 await db.exec('rollback');assert.equal(await revision(),before);
 await db.exec("insert into work_orders values(gen_random_uuid(),'"+hotel+"','committed')");
 assert.notEqual(await revision(),before);
 await db.exec("select set_config('test.uid','"+user+"',false); set role authenticated;");
 const privateRows=(await db.query('select user_id from cmpri_event_signals')).rows;
 assert.deepEqual(privateRows,[{user_id:user}]);
 await assert.rejects(()=>db.query('select * from cmpri_resource_revisions'),/permission denied/);
 await assert.rejects(()=>db.query('select * from cmpri_notification_events'),/permission denied/);
 await db.exec('reset role');
 const oldSignal=(await db.query('select revision from cmpri_event_signals where user_id=$1',[user])).rows[0].revision;
 await db.query('delete from hotel_members where user_id=$1',[user]);
 assert.notEqual((await db.query('select revision from cmpri_event_signals where user_id=$1',[user])).rows[0].revision,oldSignal,'deleted membership wakes its former owner');
 await db.query('insert into hotel_members values($1,$2,true)',[hotel,user]);
 await db.exec("insert into cmpri_work_order_history values(gen_random_uuid(),'"+hotel+"','created')");
 const claimed=(await db.query('select * from cmpri_claim_notification_events($1,100)',[hotel])).rows;
 assert.equal(claimed.length,1);
 assert.equal((await db.query('select * from cmpri_claim_notification_events($1,100)',[hotel])).rows.length,0);
 assert.equal((await db.query('select * from cmpri_claim_notification_events($1,100)',[other])).rows.length,0);
 await db.query("update cmpri_notification_events set lease_until=now()-interval '1 second' where id=$1",[claimed[0].id]);
 const replay=(await db.query('select * from cmpri_claim_notification_events($1,100)',[hotel])).rows[0];
 assert.equal(replay.id,claimed[0].id);assert.notEqual(replay.lease_token,claimed[0].lease_token);
 await assert.rejects(()=>db.exec("insert into room_operations values(gen_random_uuid(),'"+hotel+"','Occupied')"),/complete snapshot import/);
 await db.exec("begin; select set_config('cmpri.snapshot_import','on',true); insert into room_operations values(gen_random_uuid(),'"+hotel+"','Occupied'); commit;");
 await db.query('select cmpri_reconcile_room_operations()');
 assert.equal((await db.query('select room_status from room_operations')).rows[0].room_status,'Occupied');
 await assert.rejects(()=>db.exec("update room_operations set room_status='Vacant Dirty'"),/complete snapshot import/);
 }finally{await db.close();}
});
test('revision recovery ignores duplicates and unchanged snapshots but catches missed commits',()=>{
 const rows=[{resource:'room-operations',scope:'*',revision:'import-a'},{resource:'notifications',scope:user,revision:'n-a'}];
 const first=changedResources({},rows);assert.equal(first.changed.size,2);
 assert.equal(changedResources(first.next,rows).changed.size,0);
 const recovered=changedResources(first.next,[rows[0],{...rows[1],revision:'n-b'}]);
 assert.deepEqual([...recovered.changed],['notifications']);
});
